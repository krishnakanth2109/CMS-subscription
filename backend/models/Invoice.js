import mongoose from 'mongoose';

const invoiceSchema = new mongoose.Schema(
  {
    tenantOwnerId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
    },
    invoiceNumber: {
      type: String,
      required: true,
    },
    invoiceDate: {
      type: Date,
      required: true,
    },
    clientId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Client',
      required: true,
    },
    clientName: {
      type: String,
      required: true,
    },
    candidates: [
      {
        candidateProfileId: {
          type: mongoose.Schema.Types.ObjectId,
          ref: 'Candidate',
        },
        name: { type: String, required: true },
        role: { type: String },
        joiningDate: { type: Date },
        actualSalary: { type: Number },
        percentage: { type: Number },
        payment: { type: Number },
      }
    ],
    candidateCount: {
      type: Number,
      required: true,
    },
    subtotal: {
      type: Number,
      required: true,
    },
    cgstPercentage: {
      type: Number,
      default: 0,
    },
    cgstAmount: {
      type: Number,
      default: 0,
    },
    sgstPercentage: {
      type: Number,
      default: 0,
    },
    sgstAmount: {
      type: Number,
      default: 0,
    },
    grandTotal: {
      type: Number,
      required: true,
    },
    accountType: {
      type: String,
      required: true,
    },
    accountDetails: {
      accountNumber: String,
      name: String,
      bank: String,
      branch: String,
      ifsc: String,
      pan: String,
      gst: String,
    },
    file: {
      url: { type: String, required: true },
      publicId: { type: String, required: true },
      fileName: { type: String, required: true },
      mimeType: { type: String, required: true },
      size: { type: Number, required: true },
    },
    format: {
      type: String,
      default: 'pdf',
    },
    generatedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
    },
    isAutogenerated: {
      type: Boolean,
      default: false,
    },
    // Stores agreement-sourced metadata for auto-generated invoices
    agreementData: {
      lockingPeriod: { type: String },
      commissionPercentage: { type: Number },
      agreementCompanyId: { type: String },
    },
  },
  {
    timestamps: true,
  }
);

// Unique compound index: unique invoice number per tenant
invoiceSchema.index({ tenantOwnerId: 1, invoiceNumber: 1 }, { unique: true });
invoiceSchema.index({ createdAt: -1 });

const Invoice = mongoose.models.Invoice || mongoose.model('Invoice', invoiceSchema);
export default Invoice;
